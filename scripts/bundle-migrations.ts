/**
 * Compiles drizzle-kit's SQL migrations into a TS module so they ship inside
 * whatever bundle imports @autoply/core (Next.js server, worker, CLI) without
 * relying on files being present at a known path at runtime.
 *
 * Run via `pnpm db:generate`.
 */
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(import.meta.dirname, "..", "packages", "core", "drizzle");
const out = join(import.meta.dirname, "..", "packages", "core", "src", "db", "migrations.generated.ts");

const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort();

const entries = files.map((f) => {
  const statements = readFileSync(join(dir, f), "utf8")
    .split("--> statement-breakpoint")
    .map((s) => s.trim())
    .filter(Boolean);
  return { tag: f.replace(/\.sql$/, ""), statements };
});

writeFileSync(
  out,
  `// Generated by scripts/bundle-migrations.ts. Do not edit.\nexport const MIGRATIONS: { tag: string; statements: string[] }[] = ${JSON.stringify(entries, null, 2)};\n`,
);
console.log(`Bundled ${entries.length} migration(s) into ${out}`);
